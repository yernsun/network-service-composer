import { chromium } from '../frontend/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
let raw='';for await(const chunk of process.stdin)raw+=chunk;
const input=JSON.parse(raw);raw='';
const browser=await chromium.launch({executablePath:process.env.CHROME_BIN || '/usr/bin/google-chrome',args:['--no-sandbox'],headless:true});
try{
 const context=await browser.newContext({ignoreHTTPSErrors:true,locale:'en-US',viewport:{width:1280,height:900}});
 const page=await context.newPage();
 await page.goto(input.url+'/login');
 await page.locator('#username').fill('admin');
 await page.locator('#password').fill(input.password);
 await Promise.all([page.waitForURL(url=>url.pathname!='/login',{timeout:30000}),page.locator('.auth-card button[type=submit]').click()]);
 const session=(await context.cookies()).find(cookie=>cookie.name==='nsc_session');
 assert(session?.secure&&session.httpOnly,'HTTPS session protection is missing');
 await page.goto(input.url+'/projects/all/environments/all/certificates?perspective=ops');
 await page.locator('[data-certificate-id="'+input.certificate_id+'"]').waitFor({state:'visible',timeout:30000});
 await page.locator('#certificate-domain-filter').fill(input.ip);
 assert.equal(await page.locator('[data-certificate-id]').count(),1,'IP certificate filter did not retain the console asset');
 await page.locator('#certificate-domain-filter').fill('');
 await page.locator('[data-testid=self-signed-certificate] > button').click();
 await page.getByTestId('self-signed-pool').selectOption(input.pool_id);
 await page.getByTestId('self-signed-ips').fill('192.0.2.99');
 assert.equal(await page.getByTestId('self-signed-years').inputValue(),'20');
 const responsePromise=page.waitForResponse(response=>response.url().endsWith('/api/v1/certificates/self-signed')&&response.request().method()==='POST');
 await page.getByTestId('self-signed-submit').click();
 const response=await responsePromise;
 assert.equal(response.status(),201,'IP-only certificate creation failed');
 const body=await response.json();
 assert.deepEqual(body.data.domains,[]);
 assert.deepEqual(body.data.ip_addresses,['192.0.2.99']);
 const expires=new Date(body.data.not_after);const current=new Date();
 assert(expires.getUTCFullYear()-current.getUTCFullYear()===20,'certificate did not use the default twenty years');
 await page.locator('[data-certificate-id="'+body.data.id+'"]').waitFor({state:'visible',timeout:15000});
 await page.locator('#certificate-domain-filter').fill('192.0.2.99');
 assert.equal(await page.locator('[data-certificate-id]').count(),1,'new IP asset was not refreshed and filtered');
 const horizontal=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
 assert.equal(horizontal,false,'certificate page overflows at the supported desktop viewport');
 await context.close();
 process.stdout.write(JSON.stringify({status:'PASS',checks:['initial_browser_login_https_cookie','console_certificate_asset_and_ip_filter','ip_only_certificate_creation_defaults_twenty_years','creation_refresh_and_desktop_layout']}));
}finally{await browser.close();}
