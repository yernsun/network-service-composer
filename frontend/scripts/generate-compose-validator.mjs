import { readFile, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
const schema = JSON.parse(await readFile(new URL('../../internal/composecheck/compose-spec.json', import.meta.url), 'utf8'))
const ajv = new Ajv2020({ allErrors: true, strict: false, validateFormats: false, code: { source: true, esm: true, lines: true } })
let output = standaloneCode(ajv, ajv.compile(schema))
// Ajv's ESM export mode retains CommonJS runtime helper imports. Convert only
// those generated imports so Vite and native Node consume the same artifact.
output = output.replace(/const (\w+) = require\("(ajv\/dist\/runtime\/[^" ]+)"\)\.default;/g, (_, name, path) => `import ${name}Module from '${path}.js';\nconst ${name} = ${name}Module.default || ${name}Module;`)
assert(!output.includes('require('), 'Unexpected Ajv runtime import; review the generator before updating')
output = '// Generated by scripts/generate-compose-validator.mjs from the unmodified official schema. Do not edit.\n' + output
const file = new URL('../src/compose/schema.generated.js', import.meta.url)
if (process.argv.includes('--check')) assert.equal(await readFile(file, 'utf8'), output, 'Run npm run compose:generate')
else await writeFile(file, output)
